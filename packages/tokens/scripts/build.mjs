#!/usr/bin/env node
// Builds Blip's tokens from the W3C DTCG 2025.10 sources and resolver: validates them, checks contrast, and
// writes CSS, JSON, JS/TS, Android, iOS and Figma outputs. No dependencies. The work is done in tokens.mjs, which the
// blip-tokens command (cli.mjs) shares, so a theme passes the same checks.
//
// Usage: node scripts/build.mjs [--check]   (--check validates and checks contrast without writing)

import { writeFileSync, mkdirSync, rmSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { ROOT, readTokens, formatProblems, formatReport, outputs } from "./tokens.mjs";

const DIST = join(ROOT, "dist");
const HEADER = "Blip tokens. Generated by packages/tokens/scripts/build.mjs from the DTCG sources: do not edit.";

const model = readTokens();
if (model.problems.length) {
  process.stderr.write(formatProblems(model.problems));
  process.exit(1);
}
console.log(formatReport(model));
if (process.argv.includes("--check")) process.exit(0);

rmSync(DIST, { recursive: true, force: true });
for (const [file, text] of Object.entries(outputs(model, HEADER))) {
  mkdirSync(dirname(join(DIST, file)), { recursive: true });
  writeFileSync(join(DIST, file), text);
}
console.log(`Wrote ${relative(process.cwd(), DIST)}: css, json, js, android, ios, figma (${model.tokens.length} tokens, ${model.schemes.length} schemes, ${model.pixels.length} pixel sizes).`);
