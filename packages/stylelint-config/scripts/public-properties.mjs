#!/usr/bin/env node
/**
 * Writes public-properties.json: the --pp-* custom properties Blip's packages make public, for the
 * blip/known-tokens rule. A property is public when a package's CSS declares it (--pp-r: 4) or registers it
 * (@property), or when a package documents it: in a CSS comment, or in its docs. Tokens are left
 * out (the rule reads them from @jaatster/blip-tokens/manifest.json).
 *
 *   node scripts/public-properties.mjs          (run by this package's build)
 */
import { readFileSync, readdirSync, statSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";

const HERE = dirname(fileURLToPath(import.meta.url));
const PACKAGES = join(HERE, "..", "..");
const tokens = new Set(createRequire(import.meta.url)("@jaatster/blip-tokens/manifest.json").map((t) => t.cssVar));

const files = (dir, ext) => {
  if (!existsSync(dir)) return [];
  return readdirSync(dir).flatMap((f) => {
    const p = join(dir, f);
    return statSync(p).isDirectory() ? files(p, ext) : f.endsWith(ext) ? [p] : [];
  });
};

const found = new Set();
const add = (name) => {
  if (!name.endsWith("-") && !tokens.has(name)) found.add(name);
};
for (const pkg of readdirSync(PACKAGES)) {
  for (const file of files(join(PACKAGES, pkg, "src"), ".css")) {
    const css = readFileSync(file, "utf8");
    for (const m of css.matchAll(/(?:^|[;{\s])(--pp-[a-z0-9-]+)\s*:/g)) add(m[1]);
    for (const m of css.matchAll(/@property\s+(--pp-[a-z0-9-]+)/g)) add(m[1]);
    for (const c of css.matchAll(/\/\*[\s\S]*?\*\//g)) for (const m of c[0].matchAll(/--pp-[a-z0-9-]+/g)) add(m[0]);
  }
  for (const file of files(join(PACKAGES, pkg, "docs"), ".md")) {
    // Docs name properties in code (tables, examples); a wildcard like `--pp-space-N` leaves "--pp-space-", which
    // add() skips.
    for (const m of readFileSync(file, "utf8").matchAll(/--pp-[a-z0-9-]+/g)) add(m[0]);
  }
}

const properties = [...found].sort();
writeFileSync(join(HERE, "..", "public-properties.json"), `${JSON.stringify({ about: "Public --pp-* custom properties of the Blip packages (not tokens). Generated by scripts/public-properties.mjs.", properties }, null, 2)}\n`);
console.log(`public-properties.json: ${properties.length} public properties`);
